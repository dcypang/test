# ---------------------------------------------------------------------------
# Oracles
# ---------------------------------------------------------------------------

class PerfectOracle:
    """Knows every queue's true length at every moment of the day.

    Not a strategy anybody can run -- it is the ceiling that real strategies
    are measured against.
    """

    def __init__(self, trace_source, catalog: Catalog):
        self.src = trace_source
        self.cat = catalog
        self._cache: dict = {}

    def _posted(self, ride_id: str, minute: int) -> float | None:
        return self.src.wait_at(ride_id, int(minute))

    def expected_queue_min(self, ride_id: str, arrive_minute: int) -> float:
        key = (ride_id, int(arrive_minute) // 5)
        hit = self._cache.get(key)
        if hit is not None:
            return hit
        w = self._posted(ride_id, arrive_minute)
        val = 240.0 if w is None else max(5.0, w * POSTED_BIAS)
        self._cache[key] = val
        return val

    def single_rider_wait(self, ride_id: str, at_minute: int) -> float | None:
        a = self.cat.get(ride_id)
        if a is None or not a.single_rider:
            return None
        w = self._posted(ride_id, at_minute)
        if w is None:
            return None
        return max(5.0, min(w, w * 0.33 + 5))

    def premier_return(self, ride_id: str, book_minute: int) -> tuple[int, float] | None:
        a = self.cat.get(ride_id)
        if a is None or not a.premier_access:
            return None
        w = self._posted(ride_id, book_minute) or 30
        lead = int(min(180, 20 + 0.55 * w))
        return book_minute + lead, min(20.0, 5 + 0.12 * w)

    def availability(self, ride_id: str, at_minute: int) -> float:
        return 0.0 if self._posted(ride_id, at_minute) is None else 1.0


