class Strategy:
    name = "base"

    def plan(self, catalog: Catalog, cfg: TripConfig, truth, walk: WalkMatrix,
             store: Store | None) -> Plan:
        raise NotImplementedError


class OptimizerStrategy(Strategy):
    """The real thing: replans through the day on live data only."""

    name = "optimizer_online"

    def __init__(self, replan_interval: int | None = None):
        self.replan_interval = replan_interval

    def plan(self, catalog, cfg, truth, walk, store) -> Plan:
        interval = self.replan_interval or cfg.strategy.replan_interval_min
        forecaster = Forecaster.from_catalog(catalog, cfg, store)
        executor = Executor(catalog, cfg, truth, walk)
        # Replans are frequent and only the next move has to be right, so they
        # run at a narrower beam than the once-a-day opening plan.
        replan_cfg = cfg.with_overrides(
            strategy=dataclasses.replace(cfg.strategy,
                                         beam_width=cfg.strategy.replan_beam_width))

        clock = cfg.day_start()
        end_of_day = cfg.day_end()
        realised: list[PlanItem] = []
        abandoned = 0
        seen: set[str] = set()
        adult_seen: set[str] = set()
        loc = {0: WalkMatrix.ENTRANCE, 1: WalkMatrix.ENTRANCE}
        start = {0: clock, 1: clock}
        # Premier Access windows already bought carry across replans, as does
        # the money spent on them.
        pa_holds: tuple = ()
        pa_used = 0

        guard = 0
        while guard < 400:
            guard += 1
            # The party replans whenever the earlier of the two tracks comes
            # free -- that is the moment somebody has to decide what is next.
            clock = min(start[0], start[1])
            if clock >= end_of_day:
                break

            # Only what the party could actually see at this moment. Nothing
            # from later in the day is visible to the planner.
            snapshot = {
                rid: (clock, truth.wait_at(rid, clock)) for rid in catalog.ids()
            }
            forecaster.observe(snapshot)

            live_holds = tuple(h for h in pa_holds if h[0] not in seen)
            remaining_must = tuple(m for m in cfg.must_do if m not in seen)
            cursor_cfg = replan_cfg.with_overrides(must_do=remaining_must)

            opt = Optimizer(catalog, cursor_cfg, forecaster, walk)
            opt.resume_from(
                t0=start[0], t1=start[1], loc0=loc[0], loc1=loc[1],
                child_done=frozenset(seen), adult_done=frozenset(adult_seen),
                pa_holds=live_holds, pa_used=pa_used,
                lunch_done=any(i.kind == "meal" for i in realised),
            )
            plan = opt.solve()
            if not plan.items:
                break

            horizon = min(end_of_day, clock + interval)
            chunk, stop, st = executor.run(plan, upto=horizon,
                                           clock0=start, loc0=loc)
            abandoned += st["abandoned"]

            if not chunk.items:
                # Nothing was worth committing to; idle both tracks forward so
                # the loop cannot spin on the same minute forever.
                start = {tr: max(v, clock + 10) for tr, v in start.items()}
                continue

            realised.extend(chunk.items)
            for i in chunk.items:
                if i.kind == "ride" and i.ride_id:
                    (seen if i.group & CHILD else adult_seen).add(i.ride_id)
                elif i.kind == "book_pa" and i.ride_id and i.return_minute is not None:
                    pa_holds += ((i.ride_id, i.return_minute, float(i.predicted_wait)),)
                    pa_used += 1
            progressed = False
            for tr in (0, 1):
                if st["clock"][tr] is not None and st["clock"][tr] > start[tr]:
                    start[tr] = st["clock"][tr]
                    progressed = True
                loc[tr] = st["loc"][tr]
            if not progressed:
                start = {tr: max(v, clock + 10) for tr, v in start.items()}

        out = Plan(items=realised, value=sum(i.value for i in realised))
        out.notes.append(
            f"online replans={guard} interval={interval}min "
            f"abandoned={abandoned} premier_access_bought={pa_used}"
        )
        return out


class OracleStrategy(Strategy):
    """Perfect foresight. The ceiling, not a plan anyone can follow."""

    name = "oracle_upper_bound"

    def plan(self, catalog, cfg, truth, walk, store) -> Plan:
        oracle = PerfectOracle(truth, catalog)
        return Optimizer(catalog, cfg, oracle, walk).solve()


class GreedyNearestStrategy(Strategy):
    """What a family does with the official app open: from wherever you are,
    go to whatever has the shortest wait right now. No lookahead at all."""

    name = "greedy_shortest_wait"

    def plan(self, catalog, cfg, truth, walk, store) -> Plan:
        items: list[PlanItem] = []
        clock = cfg.day_start()
        loc = WalkMatrix.ENTRANCE
        done: set[str] = set()
        height = cfg.party.child_height_cm
        lunch_done = False
        lunch_at = 12 * 60 + 30

        while clock < cfg.day_end():
            if not lunch_done and clock >= lunch_at:
                items.append(PlanItem("meal", None, "Lunch", "DLP", "", EVERYONE,
                                      clock, clock, clock + cfg.lunch_window[2], ""))
                clock += cfg.lunch_window[2]
                lunch_done = True
                continue
            best = None
            for a in catalog:
                if a.id in done or not a.admits(height) or a.id in cfg.skip:
                    continue
                w = truth.wait_at(a.id, clock)
                if w is None:
                    continue
                walk_min = walk.int_minutes(loc, a.id, True)
                cost = walk_min + w * POSTED_BIAS + a.duration_min
                if best is None or cost < best[0]:
                    best = (cost, a, walk_min, w)
            if best is None:
                clock += 15
                continue
            cost, a, walk_min, w = best
            arrive = clock + walk_min
            board = int(arrive + w * POSTED_BIAS)
            end = board + a.duration_min
            if end > cfg.close_minute(a.park):
                break
            items.append(PlanItem("ride", a.id, a.name, a.park, a.land, FAMILY,
                                  clock, board, end, "standby",
                                  predicted_wait=int(w), actual_wait=int(w),
                                  track=0, value=a.appeal * cfg.strategy.child_value_weight,
                                  walk_min=walk_min))
            done.add(a.id)
            clock, loc = end, a.id
        return Plan(items=items, value=sum(i.value for i in items))


class PopularityRouteStrategy(Strategy):
    """The internet's advice: rope-drop the headliners in popularity order and
    work down the list, land by land. Fixed before you arrive; ignores the day."""

    name = "fixed_popularity_route"

    def plan(self, catalog, cfg, truth, walk, store) -> Plan:
        height = cfg.party.child_height_cm
        order = sorted(
            (a for a in catalog if a.admits(height) and a.id not in cfg.skip),
            key=lambda a: (-a.appeal, a.typical_peak_wait),
        )
        items: list[PlanItem] = []
        clock = cfg.day_start()
        loc = WalkMatrix.ENTRANCE
        lunch_done = False
        for a in order:
            if not lunch_done and clock >= 12 * 60 + 30:
                items.append(PlanItem("meal", None, "Lunch", "DLP", "", EVERYONE,
                                      clock, clock, clock + cfg.lunch_window[2], ""))
                clock += cfg.lunch_window[2]
                lunch_done = True
            walk_min = walk.int_minutes(loc, a.id, True)
            arrive = max(clock + walk_min, cfg.open_minute(a.park))
            w = truth.wait_at(a.id, arrive)
            if w is None:
                continue
            board = int(arrive + w * POSTED_BIAS)
            end = board + a.duration_min
            if end > cfg.close_minute(a.park):
                continue
            items.append(PlanItem("ride", a.id, a.name, a.park, a.land, FAMILY,
                                  clock, board, end, "standby",
                                  predicted_wait=int(w), actual_wait=int(w),
                                  track=0, value=a.appeal * cfg.strategy.child_value_weight,
                                  walk_min=walk_min))
            clock, loc = end, a.id
        return Plan(items=items, value=sum(i.value for i in items))


DEFAULT_STRATEGIES: list[Strategy] = [
    OptimizerStrategy(),
    GreedyNearestStrategy(),
    PopularityRouteStrategy(),
    OracleStrategy(),
]


