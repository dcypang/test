def score(plan: Plan, cfg: TripConfig, day: str, name: str, abandoned: int = 0) -> DayResult:
    child = [i for i in plan.rides() if i.group & CHILD]
    distinct = {i.ride_id for i in child}
    must = set(cfg.must_do)
    return DayResult(
        day=day, strategy=name, executed=plan,
        child_rides=len(child),
        distinct=len(distinct),
        must_done=len(must & distinct),
        must_total=len(must),
        family_queue_min=sum(i.wait_min for i in plan.rides(track=0)),
        walk_min=sum(i.walk_min for i in plan.items),
        value=plan.value,
        abandoned=abandoned,
    )


def backtest_day(catalog: Catalog, cfg: TripConfig, truth, day: str,
                 strategies: list[Strategy] | None = None,
                 store: Store | None = None) -> list[DayResult]:
    strategies = strategies or DEFAULT_STRATEGIES
    walk = WalkMatrix(catalog, cfg.party.walk_speed_family_mps,
                      cfg.party.walk_speed_adult_mps)
    executor = Executor(catalog, cfg, truth, walk)
    results = []
    for strat in strategies:
        plan = strat.plan(catalog, cfg, truth, walk, store)
        if isinstance(strat, OptimizerStrategy):
            # Already executed against the truth during its own replan loop.
            executed, abandoned = plan, 0
        else:
            executed, _, st = executor.run(plan)
            abandoned = st["abandoned"]
        results.append(score(executed, cfg, day, strat.name, abandoned))
    return results


def simulated_days(catalog: Catalog, cfg: TripConfig, n: int = 12,
                   seed: int = 1234) -> list[tuple[str, SimulatedSource, float]]:
    """A spread of plausible days around the trip date.

    Crowd levels are drawn across the range late November actually produces --
    quiet midweek days through busy Christmas-season weekends -- so a strategy
    cannot win by being tuned to one crowd level.
    """
    import random
    rng = random.Random(seed)
    out = []
    for k in range(n):
        d = cfg.trip_date - timedelta(days=7 * k)
        crowd = rng.choice([3.5, 4.5, 5.0, 5.5, 6.0, 6.5, 7.0, 7.5, 8.5])
        traces = simulate_day(catalog, d, crowd_index=crowd,
                              open_min=cfg.open_minute("DLP"),
                              close_min=cfg.close_minute("DLP"),
                              seed=seed + k)
        out.append((d.isoformat(), SimulatedSource(catalog, traces), crowd))
    return out


@dataclass
class BacktestReport:
    rows: list[DayResult] = field(default_factory=list)
    days: list[str] = field(default_factory=list)
    crowd: dict[str, float] = field(default_factory=dict)

    def by_strategy(self) -> dict[str, list[DayResult]]:
        out: dict[str, list[DayResult]] = {}
        for r in self.rows:
            out.setdefault(r.strategy, []).append(r)
        return out

    def aggregate(self) -> list[dict]:
        groups = self.by_strategy()
        oracle = {r.day: r.value for r in groups.get(OracleStrategy.name, [])}
        out = []
        for name, rows in groups.items():
            gaps = [rows_value_ratio(r, oracle) for r in rows]
            gaps = [g for g in gaps if g is not None]
            out.append({
                "strategy": name,
                "days": len(rows),
                "mean_value": round(statistics.fmean(r.value for r in rows), 1),
                "mean_child_rides": round(statistics.fmean(r.child_rides for r in rows), 1),
                "mean_distinct": round(statistics.fmean(r.distinct for r in rows), 1),
                "must_do_rate": round(
                    statistics.fmean(r.must_done / r.must_total if r.must_total else 1.0
                                     for r in rows), 3),
                "mean_queue_min": round(statistics.fmean(r.family_queue_min for r in rows)),
                "mean_walk_min": round(statistics.fmean(r.walk_min for r in rows)),
                "pct_of_oracle": round(100 * statistics.fmean(gaps), 1) if gaps else None,
                "worst_day_pct": round(100 * min(gaps), 1) if gaps else None,
            })
        out.sort(key=lambda r: -(r["pct_of_oracle"] or 0))
        return out

    def render(self) -> str:
        rows = self.aggregate()
        head = (f"{'strategy':24} {'days':>4} {'value':>7} {'rides':>6} {'uniq':>5} "
                f"{'must':>6} {'queue':>6} {'walk':>5} {'%oracle':>8} {'worst':>6}")
        lines = [head, "-" * len(head)]
        for r in rows:
            lines.append(
                f"{r['strategy']:24} {r['days']:>4} {r['mean_value']:>7.1f} "
                f"{r['mean_child_rides']:>6.1f} {r['mean_distinct']:>5.1f} "
                f"{r['must_do_rate']:>6.2f} {r['mean_queue_min']:>6} "
                f"{r['mean_walk_min']:>5} "
                f"{(r['pct_of_oracle'] if r['pct_of_oracle'] is not None else 0):>8.1f} "
                f"{(r['worst_day_pct'] if r['worst_day_pct'] is not None else 0):>6.1f}"
            )
        return "\n".join(lines)


def rows_value_ratio(r: DayResult, oracle: dict[str, float]) -> float | None:
    ceiling = oracle.get(r.day)
    if not ceiling:
        return None
    return r.value / ceiling


def run_backtest(catalog: Catalog, cfg: TripConfig, days: int = 12,
                 store: Store | None = None, use_stored: bool = False,
                 strategies: list[Strategy] | None = None,
                 seed: int = 1234) -> BacktestReport:
    """Score every strategy across many days and report the optimality gap."""
    report = BacktestReport()

    if use_stored and store is not None:
        stored = store.days()
        if not stored:
            raise RuntimeError(
                "no collected days in the database yet -- run `collect` for a "
                "few days first, or drop --use-stored to backtest on simulated days"
            )
        pool = [(d, ReplaySource(store, catalog, d), None) for d in stored[-days:]]
    else:
        pool = simulated_days(catalog, cfg, n=days, seed=seed)

    for day, truth, crowd in pool:
        report.days.append(day)
        if crowd is not None:
            report.crowd[day] = crowd
        report.rows.extend(backtest_day(catalog, cfg, truth, day, strategies, store))
    return report
