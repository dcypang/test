# Execution: walking a plan through the real day
# ---------------------------------------------------------------------------

@dataclass
class DayResult:
    day: str
    strategy: str
    executed: Plan
    child_rides: int = 0
    distinct: int = 0
    must_done: int = 0
    must_total: int = 0
    family_queue_min: int = 0
    walk_min: int = 0
    value: float = 0.0
    abandoned: int = 0

    def as_row(self) -> dict:
        return {
            "day": self.day,
            "strategy": self.strategy,
            "value": round(self.value, 1),
            "child_rides": self.child_rides,
            "distinct": self.distinct,
            "must_do": f"{self.must_done}/{self.must_total}",
            "queue_min": self.family_queue_min,
            "walk_min": self.walk_min,
            "abandoned": self.abandoned,
        }


class Executor:
    """Walks a planned day through the trace of what actually happened.

    A planned 20-minute wait that turns out to be 55 pushes everything after
    it later. Rides that no longer fit before closing are dropped and counted
    as abandoned. This is what separates a schedule from a fantasy.
    """

    #: If the real queue is this many minutes longer than planned, the party
    #: gives up and the replanner picks something else.
    BAIL_THRESHOLD = 30

    def __init__(self, catalog: Catalog, cfg: TripConfig, truth, walk: WalkMatrix):
        self.cat = catalog
        self.cfg = cfg
        self.truth = truth
        self.walk = walk

    def run(self, plan: Plan, upto: int | None = None,
            clock0: dict | None = None, loc0: dict | None = None
            ) -> tuple[Plan, int, dict]:
        """Execute ``plan`` against the truth up to ``upto`` minutes.

        Returns (what actually happened, the clock when execution stopped,
        per-track end state so a replan can pick up from here).

        ``upto`` is a *commitment* horizon, not a truncation: anything the plan
        starts before it runs to completion. You cannot replan your way out of
        a queue you are already standing in -- only walk away from it, which is
        what ``BAIL_THRESHOLD`` covers.
        """
        done: list[PlanItem] = []
        abandoned = 0
        clock = dict(clock0) if clock0 else {0: None, 1: None}   # track -> free-at
        loc = dict(loc0) if loc0 else {0: WalkMatrix.ENTRANCE, 1: WalkMatrix.ENTRANCE}

        for item in sorted(plan.items, key=lambda i: (i.start, i.track)):
            tr = item.track
            start = item.start if clock[tr] is None else max(item.start, clock[tr])
            if upto is not None and start >= upto:
                break

            if item.kind != "ride":
                end = start + (item.end - item.start)
                done.append(PlanItem(**{**item.__dict__, "start": start,
                                        "board": start, "end": end}))
                clock[tr] = end
                if item.kind == "meal":
                    clock[0] = clock[1] = end
                continue

            a = self.cat[item.ride_id]
            walk = self.walk.int_minutes(loc[tr], a.id, with_child=(tr == 0))
            arrive = max(start + walk, self.cfg.open_minute(a.park))

            actual = self._actual_wait(item, arrive)
            if actual is None:
                abandoned += 1              # ride was down when they got there
                clock[tr] = arrive
                loc[tr] = a.id
                continue

            board = int(arrive + actual)
            end = board + a.duration_min
            if end > self.cfg.close_minute(a.park):
                abandoned += 1
                clock[tr] = arrive
                continue
            if actual - item.predicted_wait > self.BAIL_THRESHOLD:
                # Queue is far worse than advertised; walk away and replan.
                abandoned += 1
                clock[tr] = arrive + 5
                loc[tr] = a.id
                continue

            done.append(PlanItem(**{**item.__dict__, "start": start, "board": board,
                                    "end": end, "walk_min": walk,
                                    "actual_wait": int(actual)}))
            clock[tr] = end
            loc[tr] = a.id

        stop = max((c for c in clock.values() if c is not None), default=self.cfg.day_start())
        state = {"clock": clock, "loc": loc}
        return Plan(items=done, value=sum(i.value for i in done)), stop, {
            **state, "abandoned": abandoned}

    def _actual_wait(self, item: PlanItem, arrive: int) -> float | None:
        if item.mode == "premier":
            return float(item.predicted_wait)    # a return window is a promise
        posted = self.truth.wait_at(item.ride_id, arrive)
        if posted is None:
            return None
        if item.mode == "single_rider":
            return max(5.0, min(posted, posted * 0.33 + 5))
        return max(5.0, posted * POSTED_BIAS)


