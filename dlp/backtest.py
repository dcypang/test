"""Backtest validation: is the strategy actually any good?

A plan that looks clever on paper is worthless if it was built on wait times
that never materialised. So every strategy here is scored the same way:

1. Take a day for which we have a *complete* trace of what every queue did --
   either banked by the collector or generated by the simulator.
2. Run the strategy **online**. At each replan point the strategy is handed
   only the readings that existed at that moment. It cannot see the future.
3. Advance the party through the day using the *actual* waits from the trace,
   not the ones the strategy predicted. Plans slip, and the slip is the point.
4. Score what really happened.

The headline number is the **optimality gap**: the same day is also solved by
an oracle that is given the entire day's true waits up front. The oracle is
an upper bound on what any strategy could possibly have achieved with perfect
foresight. A strategy scoring 90% of the oracle is 10% away from the best any
planner could do, and no amount of cleverness can close a gap caused by
information that simply was not available at the time.

Baselines are included because "our strategy scores 400" means nothing on its
own. It has to beat what a reasonable family would do without any of this.
"""

